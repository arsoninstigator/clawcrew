"""the translation between the two dialects, and the published ddl staying honest.

sqlite is what the app writes; postgres is what a multi-writer deploy hosts. these
tests hold the mechanical half: placeholders, upserts with the real primary key, the
statement splitter, and the file in `docs/` matching the schema the app creates.
"""

from __future__ import annotations

import pathlib
import sys
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from core.db import SCHEMA  # noqa: E402
from core.dialect import (  # noqa: E402
    SQLITE_ONLY,
    generate_ddl,
    placeholders,
    primary_keys,
    statements,
    to_postgres,
    translate,
    upsert,
)

KEYS = primary_keys(SCHEMA)
DDL_PATH = ROOT / "crittertown" / "docs" / "schema.postgres.sql"


class PlaceholderTests(unittest.TestCase):
    def test_question_marks_become_format_specifiers(self):
        self.assertEqual(
            placeholders("select * from agents where id = ? and team_id = ?"),
            "select * from agents where id = %s and team_id = %s",
        )

    def test_a_question_mark_inside_a_literal_is_data(self):
        sql = "select * from t where q = 'why?' and id = ?"
        self.assertEqual(placeholders(sql), "select * from t where q = 'why?' and id = %s")

    def test_an_escaped_quote_keeps_the_literal_open(self):
        sql = "select 'it''s ?' as x, ? as y"
        self.assertEqual(placeholders(sql), "select 'it''s ?' as x, %s as y")

    def test_a_comment_is_not_data(self):
        sql = "-- is this a ? in a comment\nselect ? as x"
        self.assertEqual(placeholders(sql), "-- is this a ? in a comment\nselect %s as x")


class StatementTests(unittest.TestCase):
    def test_the_schema_splits_into_one_statement_per_create(self):
        parts = statements(SCHEMA)
        creates = [p for p in parts if p.lower().startswith("create table")]
        self.assertEqual(len(creates), len(KEYS))
        other = [p for p in parts if not p.lower().startswith(("create table", "create index",
                                                              "create unique index"))]
        self.assertEqual(other, [], f"unexpected statements in the schema: {other[:2]}")

    def test_a_semicolon_inside_a_literal_does_not_split(self):
        parts = statements("select 'a;b'; select 1")
        self.assertEqual(parts, ["select 'a;b'", "select 1"])

    def test_a_trailing_statement_without_a_semicolon_is_kept(self):
        self.assertEqual(statements("select 1;\nselect 2"), ["select 1", "select 2"])


class PrimaryKeyTests(unittest.TestCase):
    def test_a_text_key(self):
        self.assertEqual(KEYS["meta"], ["key"])

    def test_a_composite_key_keeps_its_order(self):
        self.assertEqual(KEYS["agent_teams"], ["agent_id", "team_id"])

    def test_an_autoincrement_key_is_still_the_key(self):
        self.assertEqual(KEYS["comms_events"], ["seq"])

    def test_every_table_declares_a_key(self):
        missing = [table for table, cols in KEYS.items() if not cols]
        self.assertEqual(missing, [], f"no primary key found for: {missing}")


class PostgresDdlTests(unittest.TestCase):
    def test_autoincrement_becomes_an_identity_column(self):
        sql = to_postgres("create table t (\n    seq integer primary key autoincrement\n);")
        self.assertIn("bigint generated by default as identity primary key", sql)
        self.assertNotIn("autoincrement", sql)

    def test_types_are_mapped(self):
        sql = to_postgres("create table t (\n    at real not null,\n    body blob\n);")
        self.assertIn("at double precision not null", sql)
        self.assertIn("body bytea", sql)

    def test_no_sqlite_token_survives(self):
        generated = to_postgres(SCHEMA).lower()
        leftovers = [token for token in SQLITE_ONLY if token in generated]
        self.assertEqual(leftovers, [], f"not portable to postgres: {leftovers}")


class UpsertTests(unittest.TestCase):
    def test_replace_becomes_update_on_the_real_key(self):
        sql = upsert("insert or replace into meta (key, value) values (?, ?)", KEYS)
        self.assertTrue(sql.startswith("insert into meta (key, value) values (?, ?)"))
        self.assertIn("on conflict (key) do update set value = excluded.value", sql)
        self.assertNotIn("insert or replace", sql)

    def test_a_composite_key_is_the_conflict_target(self):
        sql = upsert(
            "insert or replace into agent_teams (agent_id, team_id, role) values (?,?,?)", KEYS
        )
        self.assertIn("on conflict (agent_id, team_id) do update set role = excluded.role", sql)

    def test_ignore_becomes_do_nothing(self):
        sql = upsert(
            "insert or ignore into agent_teams (agent_id, team_id, role, membership, joined_date) "
            "select id, team_id, role, 'home', created_date from agents",
            KEYS,
        )
        self.assertTrue(sql.startswith("insert into agent_teams (agent_id, team_id"))
        self.assertTrue(sql.endswith("on conflict do nothing"))

    def test_a_table_with_only_key_columns_does_nothing(self):
        sql = upsert("insert or replace into meta (key) values (?)", {"meta": ["key"]})
        self.assertIn("on conflict do nothing", sql)

    def test_returning_stays_last(self):
        sql = upsert(
            "insert or replace into meta (key, value) values (?, ?) returning key", KEYS
        )
        self.assertTrue(sql.rstrip().endswith("returning key"))
        self.assertIn("on conflict (key) do update", sql)

    def test_a_plain_insert_is_untouched(self):
        sql = "insert into meta (key, value) values (?, ?)"
        self.assertEqual(upsert(sql, KEYS), sql)

    def test_translate_does_both_halves(self):
        sql = translate("insert or replace into meta (key, value) values (?, ?)", KEYS)
        self.assertIn("%s", sql)
        self.assertIn("on conflict (key) do update", sql)
        self.assertNotIn("?", sql)


class PublishedDdlTests(unittest.TestCase):
    """the file a deployer pastes into supabase. it went stale once (34 of 45 tables),
    which is exactly the kind of drift a person finds after trusting it."""

    def test_the_committed_ddl_matches_the_schema(self):
        self.assertTrue(DDL_PATH.exists(), "docs/schema.postgres.sql is missing")
        self.assertEqual(
            generate_ddl(SCHEMA),
            DDL_PATH.read_text(),
            "docs/schema.postgres.sql is stale; run `make ddl` and commit the result",
        )

    def test_the_committed_ddl_carries_every_table(self):
        text = DDL_PATH.read_text()
        missing = [table for table in KEYS if f"create table if not exists {table} (" not in text]
        self.assertEqual(missing, [], f"tables missing from the published ddl: {missing}")

    def test_the_committed_ddl_has_no_sqlite_dialect(self):
        text = DDL_PATH.read_text().lower()
        leftovers = [token for token in SQLITE_ONLY if token in text]
        self.assertEqual(leftovers, [], f"sqlite dialect in the published ddl: {leftovers}")
