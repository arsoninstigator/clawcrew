"""the two dialects, and the one place that knows them apart.

`core.db.SCHEMA` is sqlite dialect on purpose: it is the file the app writes and the
570 tests run against, and a single file with wal mode is the right default for one
machine. postgres is what you host when more than one process has to write the same
rows, and it is close enough to sqlite that the difference is four things:

* `?` placeholders instead of `%s`
* `insert or replace / insert or ignore` instead of `on conflict`
* `executescript` instead of a list of statements
* three type names, and `integer primary key autoincrement`

everything else in the schema and the queries is already portable. so this module is
mechanical, and it is the only translation step: the postgres store and `make ddl`
both call it, which is what stops the published ddl from drifting away from the
schema the app actually creates.
"""

from __future__ import annotations

import re

# sqlite tokens that must not survive into postgres ddl. the sync test reads this
# list, so adding a construct above means adding its name here.
SQLITE_ONLY = (
    "autoincrement",
    "pragma",
    "executescript",
    "insert or replace",
    "insert or ignore",
    "attach database",
)

CREATE_TABLE = re.compile(
    r"create table if not exists (\w+) \((.*?)\n\);", re.IGNORECASE | re.DOTALL
)
_UPSERT_HEADER = re.compile(
    r"^\s*insert\s+or\s+(replace|ignore)\s+into\s+(\w+)\s*\(([^)]*)\)",
    re.IGNORECASE | re.DOTALL,
)


def _walk(sql: str):
    """yield (index, char, in_literal) for every character outside a `--` comment.

    one scanner, so placeholders, statement splitting and literal detection cannot
    disagree about where a string ends.
    """
    i, n = 0, len(sql)
    in_string = False
    while i < n:
        ch = sql[i]
        if in_string:
            if ch == "'":
                if i + 1 < n and sql[i + 1] == "'":  # '' is an escaped quote
                    yield i, ch, True
                    i += 2
                    continue
                in_string = False
            yield i, ch, True
            i += 1
            continue
        if ch == "'":
            in_string = True
            yield i, ch, True
            i += 1
            continue
        if ch == "-" and i + 1 < n and sql[i + 1] == "-":
            while i < n and sql[i] != "\n":
                i += 1
            yield i, "\n", False
            i += 1
            continue
        yield i, ch, False
        i += 1


def placeholders(sql: str) -> str:
    """sqlite writes `?`, psycopg writes `%s`. a `?` inside a literal stays put."""
    out = list(sql)
    for index, ch, in_literal in _walk(sql):
        if ch == "?" and not in_literal:
            out[index] = "%s"
    return "".join(out)


def statements(sql: str) -> list[str]:
    """split a script on its semicolons, ignoring the ones inside literals."""
    parts: list[str] = []
    current: list[str] = []
    for index, ch, in_literal in _walk(sql):
        if ch == ";" and not in_literal:
            text = "".join(current).strip()
            if text:
                parts.append(text)
            current = []
            continue
        current.append(sql[index])
    tail = "".join(current).strip()
    if tail:
        parts.append(tail)
    return parts


def primary_keys(schema: str) -> dict[str, list[str]]:
    """table -> the columns that make a row unique, read out of the schema itself.

    the upsert translation needs a conflict target, and guessing one (`id` because
    most tables use it) is how a replace silently inserts a duplicate instead.
    """
    keys: dict[str, list[str]] = {}
    for table, body in CREATE_TABLE.findall(schema):
        match = re.search(r"primary key \(([^)]*)\)", body, re.IGNORECASE)
        if match:
            keys[table] = [c.strip() for c in match.group(1).split(",") if c.strip()]
            continue
        inline = re.search(r"(?m)^\s*(\w+)\s+\w[^,]*\bprimary key\b", body, re.IGNORECASE)
        keys[table] = [inline.group(1)] if inline else []
    return keys


def to_postgres(ddl: str) -> str:
    """the schema, in the dialect insforge or supabase will accept.

    types are mapped and nothing is invented: an unknown construct is left alone and
    the sync test fails, rather than being quietly dropped.
    """
    out = ddl.replace(
        "integer primary key autoincrement",
        "bigint generated by default as identity primary key",
    )
    out = re.sub(r"(?m)^(\s*\w+\s+)real\b", r"\1double precision", out)
    out = re.sub(r"(?m)^(\s*\w+\s+)blob\b", r"\1bytea", out)
    return out.strip() + "\n"


def upsert(sql: str, keys: dict[str, list[str]]) -> str:
    """`insert or replace` becomes `on conflict (<the real key>) do update`.

    `insert or ignore` becomes `do nothing`. a statement that is not one of those is
    returned unchanged, so a plain insert or update passes through.
    """
    match = _UPSERT_HEADER.match(sql)
    if not match:
        return sql
    kind, table, columns = match.group(1).lower(), match.group(2), match.group(3)
    conflict = keys.get(table) or []
    if kind == "ignore" or not conflict:
        clause = " on conflict do nothing"
    else:
        cols = [c.strip() for c in columns.split(",") if c.strip()]
        updates = [c for c in cols if c not in conflict]
        if not updates:
            clause = " on conflict do nothing"
        else:
            assignments = ", ".join(f"{c} = excluded.{c}" for c in updates)
            clause = f" on conflict ({', '.join(conflict)}) do update set {assignments}"
    header = match.group(0)
    rest = sql[match.end():]
    body = f"insert into {table} ({columns})" + rest.rstrip().rstrip(";")
    returning = re.search(r"\breturning\b", body, re.IGNORECASE)
    if returning:
        return body[: returning.start()].rstrip() + clause + " " + body[returning.start():]
    return body + clause


def translate(sql: str, keys: dict[str, list[str]]) -> str:
    """sqlite sql in, the backend's sql out. one call, both rewrites, in order."""
    return placeholders(upsert(sql, keys))


def generate_ddl(schema: str) -> str:
    """the published file, byte for byte. `make ddl` prints this; a test compares."""
    head = (
        "-- generated by scripts/export_ddl.py from core.db.SCHEMA. do not edit.\n"
        "-- sqlite is the runtime; this file is for hosting the same tables elsewhere.\n"
    )
    return head + "\n" + to_postgres(schema)
