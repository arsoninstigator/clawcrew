"""print the schema as postgres ddl, so insforge or supabase can host the rows.

`clawcrew.db.SCHEMA` is sqlite dialect on purpose: it is the file the app writes and the
tests run against. this script is the one translation step, kept mechanical so it cannot
drift: types are mapped, nothing is invented, and anything it does not know how to map it
leaves alone and reports.
"""

from __future__ import annotations

import sys

sys.path.insert(0, ".")

from clawcrew.db import SCHEMA  # noqa: E402

TYPES = {
    "real": "double precision",
    "blob": "bytea",
}


def to_postgres(sql: str) -> str:
    out = sql
    for sqlite_type, pg_type in TYPES.items():
        out = out.replace(f" {sqlite_type} ", f" {pg_type} ")
        out = out.replace(f" {sqlite_type},", f" {pg_type},")
        out = out.replace(f" {sqlite_type}\n", f" {pg_type}\n")
    out = out.replace(" integer primary key", " integer primary key")
    return out.strip() + "\n"


if __name__ == "__main__":
    print("-- generated by scripts/export_ddl.py from clawcrew.db.SCHEMA. do not edit.")
    print("-- sqlite is the runtime; this file is for hosting the same tables elsewhere.")
    print()
    print(to_postgres(SCHEMA))
